"""ค่าคงที่และค่าเผื่อสำหรับการปริ้น FDM (จูนสำหรับ Bambu Lab P2S, nozzle 0.4 mm)

ทุกค่าเป็นมิลลิเมตร (mm)

หลักคิด: ชิ้นงาน FDM จะพิมพ์ "รู" เล็กกว่าแบบเสมอ (พลาสติกบวมเข้าด้านใน)
และผิวสัมผัสสองชิ้นที่ต้องประกอบกันต้องมีช่องว่าง (clearance) เสมอ
"""

# ---- เครื่อง / หัวฉีด ----
NOZZLE = 0.4          # เส้นผ่านศูนย์กลางหัวฉีดมาตรฐานของ P2S
LAYER_HEIGHT = 0.2    # ความสูงเลเยอร์ที่ใช้บ่อยสุด
MIN_WALL = 0.8        # ผนังบางสุดที่แข็งแรงพอ (2 เส้นของ nozzle 0.4)
STRONG_WALL = 1.6     # ผนังสำหรับชิ้นส่วนรับแรง (4 เส้น)

# ---- ค่าเผื่อการสวมประกอบ (clearance ต่อ "ด้าน" ระหว่างสองผิว) ----
FIT_PRESS = 0.05      # อัดแน่น: ต้องใช้แรงกด/ค้อนยาง ยึดถาวร
FIT_TIGHT = 0.10      # แน่น: ดันเข้าด้วยมือ ไม่หลุดเอง (เช่น ฝาสแนป แกนลูกบิด)
FIT_SLIDE = 0.20      # เลื่อนได้: สวม-ถอดคล่อง แต่ไม่โยก (เช่น ฝากล่อง ลิ้นชัก)
FIT_LOOSE = 0.30      # หลวม: ขยับอิสระ (เช่น บานพับ ข้อต่อหมุน)

# ---- ชดเชยรูที่พิมพ์แล้วหด ----
# รูแนวตั้ง (แกน Z) บนเครื่อง Bambu มักเล็กกว่าแบบ ~0.1–0.3 mm
HOLE_COMP = 0.2       # ค่าชดเชยเส้นผ่านศูนย์กลางรูโดยรวม


def hole_dia(nominal: float, fit: float = 0.0) -> float:
    """เส้นผ่านศูนย์กลางรูที่ควรเขียนแบบ เพื่อให้รูจริงหลังปริ้นได้ตามต้องการ

    nominal: ขนาดแกน/สกรูจริงที่จะสอด (mm)
    fit:     clearance ต่อด้าน เช่น FIT_SLIDE ถ้าต้องการให้เลื่อนได้
    """
    return nominal + HOLE_COMP + 2 * fit
